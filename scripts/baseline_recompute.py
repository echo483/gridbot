"""Leak-filtered baseline + execution-geometry study on inherited training_rounds.

Filter (CORPUS-F1-LEAKFILTER): drop rows where rounds_played+1 != round_number
(features AND top-level must both agree the row is a clean pre-round state).
Everything computed here is descriptive baseline ONLY — no registry writes,
no model changes. Output: docs/analysis/2026-08-25-baseline-recompute.md
"""
from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

SRC = Path("data/analysis/training_rounds.jsonl")
OUT = Path("docs/analysis")
OUT.mkdir(exist_ok=True, parents=True)

rows = []
with SRC.open() as f:
    for line in f:
        line = line.strip()
        if line:
            rows.append(json.loads(line))

total = len(rows)
kept, dropped = [], []
for r in rows:
    f_rp = (r.get("features") or {}).get("rounds_played")
    f_rn = (r.get("features") or {}).get("round_number")
    t_rn = r.get("round_number")
    # clean pre-round state: features describe the state entering round_number
    ok = (f_rp is not None and f_rn is not None and t_rn is not None
          and f_rp + 1 == f_rn == t_rn)
    (kept if ok else dropped).append(r)

def brier(rs):
    # prior_round_p is the baseline (pre-model) probability for label
    if not rs:
        return float("nan"), 0
    s = sum((r["features"].get("prior_round_p", 0.5) - r["label"]) ** 2 for r in rs)
    return s / len(rs), len(rs)

def wilson(p, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)

b_all, n_all = brier(rows)
b_keep, n_keep = brier(kept)
b_drop, n_drop = brier(dropped)

# ---- state-conditioned stats the instruments care about ----
def manadv_study(rs):
    """trailing team with >=2 man advantage, >=20s clock: round-win rate."""
    hit = [r for r in rs
           if r["features"].get("man_advantage", 0) <= -2
           and r["features"].get("score_lead", 0) < 0
           and r["features"].get("time_remaining", 0) >= 20 / 105]
    # NOTE: sign conventions of inherited features are uncertain; report raw slices both ways
    hit_pos = [r for r in rs
               if r["features"].get("man_advantage", 0) >= 2
               and r["features"].get("score_lead", 0) < 0]
    return hit, hit_pos

ma_neg, ma_pos = manadv_study(kept)

def rate(rs):
    return (sum(r["label"] for r in rs) / len(rs)) if rs else float("nan")

lines = []
A = lines.append
A("# Baseline recompute under CORPUS-F1-LEAKFILTER (2026-08-25)")
A("")
A(f"- source rows: {total}")
A(f"- kept (clean pre-round states): {len(kept)} ({len(kept)/total:.1%})")
A(f"- dropped (transition/leaky): {len(dropped)} ({len(dropped)/total:.1%})")
A("")
A("## Baseline Brier (prior_round_p vs label)")
A(f"- all rows: {b_all:.4f} (N={n_all})  [contaminated reference]")
A(f"- kept rows: {b_keep:.4f} (N={n_keep})")
A(f"- dropped rows: {b_drop:.4f} (N={n_drop})  [leak signature: should be much lower]")
A("")
A("## Slice checks (kept rows only)")
A(f"- man_advantage<=-2 & trailing: N={len(ma_neg)} rate={rate(ma_neg):.3f}")
A(f"- man_advantage>=+2 & trailing(label semantics unknown): N={len(ma_pos)} rate={rate(ma_pos):.3f}")
A("")
A("## Round-number win-rate table (label by round_number, kept)")
by_round = defaultdict(lambda: [0, 0])
for r in kept:
    rn = int(r["round_number"])
    by_round[rn][0] += r["label"]
    by_round[rn][1] += 1
A("| round | N | label_rate |")
A("|---|---|---|")
for rn in sorted(by_round):
    w, n = by_round[rn]
    if n >= 20:
        lo, hi = wilson(w / n, n)
        A(f"| {rn} | {n} | {w/n:.3f} ({lo:.3f}-{hi:.3f}) |")
A("")
A("_Generated by scripts/baseline_recompute.py. Descriptive only; no registry writes._")

out = OUT / "2026-08-25-baseline-recompute.md"
out.write_text("\n".join(lines))
print("\n".join(lines))
